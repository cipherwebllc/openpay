// 各ルートの client component が参照する next-intl namespace の宣言 (単一情報源)。
//
// 背景: locale layout が <NextIntlClientProvider> に messages を渡していなかったため、
// messages/ja.json 全量 (71 namespace) が全ページの HTML に inline されていた
// (ja.html ≈ 479 KB)。ここで宣言した namespace だけを pick して渡すことで、
// ページごとに必要な分だけを配信する。
//
// 一覧の維持: ページの client 依存グラフを静的に辿って照合する
// `tests/lib/i18nClientNamespaces.test.ts` が CI のフェンス。新しい
// `useTranslations('X')` を足したら該当ルートの配列にも足すこと
// (漏らすと実行時 MISSING_MESSAGE になる)。
//
// 注意: nested な NextIntlClientProvider は messages を **マージせず置き換える**
// (use-intl IntlProvider)。そのためルート側の provider には SHARED も足して渡す
// (i18n/RouteMessages.tsx を参照)。

