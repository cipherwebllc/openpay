const PLATFORM_KEYS = Object.keys(PLATFORMS) as Exclude<SocialPlatform, 'other'>[];

function hostMatches(host: string, domain: string): boolean {
  return host === domain || host.endsWith(`.${domain}`);
}

/** URL のドメインから SNS プラットフォームを判定。不正 URL / 未知ドメインは 'other'。 */
export function detectSocialPlatform(url: string): SocialPlatform {
  let host: string;
  try {
    host = new URL(url).hostname.toLowerCase();
  } catch {
    return 'other';
  }
  for (const key of PLATFORM_KEYS) {
    if (PLATFORMS[key].domains.some((d) => hostMatches(host, d))) return key;
  }
  return 'other';
}

/** アイコンの aria-label / title 用ラベル。既知 SNS はブランド名、未知は hostname。 */
export function socialLabelFor(url: string): string {
  const platform = detectSocialPlatform(url);
  if (platform !== 'other') return PLATFORMS[platform].label;
  try {
    return new URL(url).hostname;
  } catch {
    return url;
  }
}

/** 既知 SNS の simple-icons path (24x24 viewBox)。'other' は null (表示側で globe に倒す)。 */
export function socialIconPath(platform: SocialPlatform): string | null {
  if (platform === 'other') return null;
  return PLATFORMS[platform].path;
}
